#!/usr/bin/env python3
"""CL-OPS-02: observation-only, one-hot-tail-controlled 3x3 stream programs.

DISCOVER/DEVELOP, not a native Playdead decoder. All '?' remain unknown.
Only the standard library is needed.

Two sharply separate questions:
(1) If the 27-cell tail contains one slash in each class-local three-cell
    stack, what 27 positions are fixed when it directly selects a body rail?
(2) If the corresponding trit is an actual program opcode, can nine class-
    local 3x3 body words be successive exact rotations or row/column shifts?

For (2), the first body word is a free nine-bit initial state and each later
word is generated by transforming the previous state. The *target* class's
one-hot tail selects identity/forward/backward; optional complement is a
single model-wide flag. Every unknown body bit is existentially quantified,
never guessed and incorporated as a physical observation.

The exact engine composes pure bit permutations, so all constraints reduce
to nine independent root-bit choices. Exhaustive checking of one 512-state
example guards against a mistakenly permissive constraint propagation.
"""
import argparse
from collections import Counter
import csv
import itertools
import json
from pathlib import Path

CLASSES = "ABCDEFGHI"
ART_ORDER = "IABCDEFGH"  # solved physical mosaic IAB/CDE/FGH, row-major
ORDERS = ("ABCDEFGHI", ART_ORDER)
OPERATIONS = ("rotation", "row_shift", "column_shift")


def physical(path):
    observed = ["?"] * 108
    with Path(path).open(newline="", encoding="utf-8") as handle:
        records = list(csv.DictReader(handle))
    assert len(records) == 84
    for r in records:
        serial, residue = int(r["serial"]), int(r["residue"])
        value = r["symbol"]
        assert 1 <= residue <= 108
        assert residue == (serial % 108 or 108)
        assert value in ("/", "-", ".")
        class_j = (serial - 1) % 9
        assert not r["image_class"] or r["image_class"] == CLASSES[class_j]
        i = residue - 1
        assert observed[i] in ("?", value), (residue, observed[i], value)
        observed[i] = value
    assert sum(s != "?" for s in observed) == 66
    assert sum(s != "?" for s in observed[:81]) == 54
    assert sum(s != "?" for s in observed[81:]) == 12
    assert all(s in ("?", "/", "-") for s in observed[:81])
    assert all(s in ("?", "/", ".") for s in observed[81:])
    return observed


def selector_assignments(observed):
    """Nine class-local trits, one slash in each 3-cell tail stack."""
    tail = observed[81:]
    allowed = []
    for j, c in enumerate(CLASSES):
        triple = [tail[9 * q + j] for q in range(3)]
        assert triple.count("/") <= 1
        if "/" in triple:
            candidates = (triple.index("/"),)
        else:
            candidates = tuple(q for q, v in enumerate(triple) if v == "?")
        assert candidates, (c, triple)
        allowed.append(candidates)
    vectors = tuple(dict(zip(CLASSES, q)) for q in itertools.product(*allowed))
    assert len(vectors) == 18, len(vectors)
    return vectors, dict(zip(CLASSES, map(list, allowed)))


def direct_sample(observed, assignments, strict_frozen=False):
    """Tail trit selects same depth in all three 27-cell body quarters."""
    body = observed[:81]
    possible = []
    forced = []
    for q in range(3):
        line = []
        detail = []
        for j, c in enumerate(CLASSES):
            alternatives = {body[q * 27 + 9 * a[c] + j] for a in assignments}
            detail.append("".join(sorted(alternatives)))
            line.append(next(iter(alternatives)) if len(alternatives) == 1 and
                        "?" not in alternatives else "?")
        possible.append(detail)
        forced.append("".join(line))
    count = sum(ch != "?" for row in forced for ch in row)
    if strict_frozen:
        assert forced == ["?/-///?-?", "?/////?-?", "?-??//?//"], forced
        assert count == 17, count
    return {"forced_rows": forced, "forced_known": count,
            "unresolved": 27 - count, "possibilities": possible}


def permute_source_to_destination(operation, trit):
    result = []
    for j in range(9):
        x, y = j % 3, j // 3
        if operation == "rotation":
            if trit == 1:  # clockwise
                x, y = 2 - y, x
            elif trit == 2:  # counterclockwise
                x, y = y, 2 - x
        elif operation == "row_shift":
            y = (y + trit) % 3
        else:
            assert operation == "column_shift"
            x = (x + trit) % 3
        result.append(y * 3 + x)
    assert sorted(result) == list(range(9))
    return result


def root_constraints(body, order, operation, invert_each_step, selector):
    """Compose every word as (root-bit index, XOR complement)."""
    mapping = {order[0]: [(i, 0) for i in range(9)]}
    for previous, current in zip(order, order[1:]):
        perm = permute_source_to_destination(operation, selector[current])
        next_map = [None] * 9
        for input_j, (root_index, flip) in enumerate(mapping[previous]):
            next_map[perm[input_j]] = root_index, flip ^ invert_each_step
        mapping[current] = next_map
    counts = [[0, 0] for _ in range(9)]
    for class_j, c in enumerate(CLASSES):
        for depth in range(9):
            observed = body[9 * depth + class_j]
            if observed == "?":
                continue
            root_index, flip = mapping[c][depth]
            root_bit = int(observed == "/") ^ flip
            counts[root_index][root_bit] += 1
    assert sum(sum(s) for s in counts) == 54
    return counts, mapping


def score(body, order, operation, invert_each_step, selector):
    counts, _ = root_constraints(
        body, order, operation, invert_each_step, selector)
    contradictions = sum(min(a, b) for a, b in counts)
    exact_root_states = (
        (1 << sum(a == b for a, b in counts)) if contradictions == 0 else 0)
    return contradictions, exact_root_states


def brute_root_score(body, order, operation, invert_each_step, selector):
    """Independent 2^9 explicit interpreter to cross-check a model's score."""
    root_mapping = {order[0]: list(range(9))}
    # We use a different path from the symbolic root-map evaluation:
    # simulate each actual 9-bit initial word and compare known input bits.
    def simulate(root_bits):
        words = {order[0]: root_bits[:]}
        for previous, current in zip(order, order[1:]):
            target = [None] * 9
            permutation = permute_source_to_destination(operation, selector[current])
            for j, b in enumerate(words[previous]):
                target[permutation[j]] = b ^ invert_each_step
            words[current] = target
        return words

    optimum = 54
    zero_states = 0
    for n in range(512):
        root_bits = [(n >> bit) & 1 for bit in range(9)]
        words = simulate(root_bits)
        mismatches = 0
        for j, c in enumerate(CLASSES):
            for d in range(9):
                symbol = body[9 * d + j]
                if symbol != "?" and words[c][d] != int(symbol == "/"):
                    mismatches += 1
        optimum = min(optimum, mismatches)
        zero_states += mismatches == 0
    return optimum, zero_states


def model_family(body, selectors):
    results = []
    for order, operation, flip in itertools.product(ORDERS, OPERATIONS, (0, 1)):
        entries = [score(body, order, operation, flip, s)
                   for s in selectors]
        results.append({
            "order": order,
            "operation": operation,
            "global_invert_each_step": flip,
            "best_conflicts": min(p[0] for p in entries),
            "exact_tail_and_root_completions": sum(p[1] for p in entries),
        })
    assert len(results) == 12
    return results


class LCG:
    def __init__(self, seed=0x7A5B8321):
        self.state = seed

    def rnd(self):
        self.state = (self.state * 1664525 + 1013904223) & 0xFFFFFFFF
        return self.state / 4294967296

    def shuffle(self, array):
        for i in range(len(array) - 1, 0, -1):
            j = int(self.rnd() * (i + 1))
            array[i], array[j] = array[j], array[i]


def shuffled_body(body, generator):
    """Within each nine-serial frame, preserve observation mask and symbol counts."""
    out = []
    for q in range(9):
        frame = list(body[9 * q:9 * q + 9])
        values = [s for s in frame if s != "?"]
        generator.shuffle(values)
        read = iter(values)
        out += [next(read) if s != "?" else "?" for s in frame]
    return "".join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--observations", default="data/observations.csv")
    parser.add_argument("--null-replicates", type=int, default=500)
    parser.add_argument("--direct-null-replicates", type=int, default=5000)
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args()

    marks = physical(args.observations)
    selectors, allowed = selector_assignments(marks)
    body = "".join(marks[:81])
    direct = direct_sample(marks, selectors, strict_frozen=True)
    direct_rng = LCG()
    direct_null = []
    for _ in range(args.direct_null_replicates):
        shuffled = list(shuffled_body(body, direct_rng)) + marks[81:]
        direct_null.append(direct_sample(shuffled, selectors)["forced_known"])
    direct_ge = sum(x >= direct["forced_known"] for x in direct_null)
    if args.direct_null_replicates == 5000:
        assert direct_ge == 1052, direct_ge
    all_models = model_family(body, selectors)

    assert [(x["best_conflicts"]) for x in all_models] == [
        17, 16, 14, 17, 18, 16, 17, 14, 13, 19, 16, 16], all_models
    assert all(x["exact_tail_and_root_completions"] == 0 for x in all_models)
    best = min(x["best_conflicts"] for x in all_models)
    assert best == 13

    # Independent 512-state check on a variant (first model, first tail).
    first = all_models[0]
    symbolic = score(body, first["order"], first["operation"],
                     first["global_invert_each_step"], selectors[0])
    assert symbolic == brute_root_score(
        body, first["order"], first["operation"],
        first["global_invert_each_step"], selectors[0])

    rng = LCG()
    nulls = []
    for _ in range(args.null_replicates):
        permuted = shuffled_body(body, rng)
        nulls.append(min(p["best_conflicts"]
                         for p in model_family(permuted, selectors)))
    at_least_as_close = sum(x <= best for x in nulls)
    if args.null_replicates == 500:
        assert at_least_as_close == 325, at_least_as_close

    result = {
        "research_mode": "DISCOVER/DEVELOP; not an authored instruction set",
        "records": 84,
        "unique_positions": 66,
        "unknown_positions": 42,
        "conditional_onehot_tail_assignments": len(selectors),
        "tail_allowed_trits": allowed,
        "direct_select_81_to_27": direct,
        "direct_select_matched_null": {
            "replicates": args.direct_null_replicates,
            "seed": "0x7A5B8321",
            "observed_forced_positions": direct["forced_known"],
            "as_many_forced_positions_or_more": direct_ge,
            "null_mean_forced_positions": (
                sum(direct_null) / len(direct_null) if direct_null else None),
            "null_histogram": dict(sorted(Counter(direct_null).items())),
        },
        "stream_model": {
            "description": "first nine-bit class-word literal; subsequent class-word = "
                           "tail-trit-selected three-way 3x3 shift/rotation of prior word",
            "models": all_models,
            "min_physical_conflicts": best,
            "models_with_exact_completions": sum(
                p["exact_tail_and_root_completions"] > 0 for p in all_models),
        },
        "matched_null": {
            "replicates": args.null_replicates,
            "seed": "0x7A5B8321",
            "control": "shuffle observed body glyphs within each 9-sticker frame; "
                       "preserve known masks, class-tail assignments and frame slash counts",
            "null_minimum_conflicts_histogram": dict(sorted(Counter(nulls).items())),
            "as_good_or_better_than_observed": at_least_as_close,
        },
    }
    if args.json:
        print(json.dumps(result, indent=2, sort_keys=True))
    else:
        print("One-hot tail completions:", len(selectors))
        print("27 direct-selected outputs:", " / ".join(direct["forced_rows"]))
        print("Fixed symbols:", direct["forced_known"], "of 27")
        print("Direct-selection matched null >= observed:", direct_ge,
              "/", args.direct_null_replicates)
        print("Best 9-word genuine instruction stream:", best,
              "physical contradictions of 54 known body symbols")
        print("Exact model completions:",
              result["stream_model"]["models_with_exact_completions"])
        print("Matched-null controls with <= observed conflicts:",
              at_least_as_close, "/", args.null_replicates)


if __name__ == "__main__":
    main()
